//! Pure descriptor for Seccomp BPF filters.

use crate::error::DomainError;
use crate::seccomp::action::SeccompAction;
use crate::seccomp::syscall::SyscallRule;
use serde::{Deserialize, Serialize};

/// Target architecture for syscall identification.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum SystemArch {
    /// x86_64 architecture (`AUDIT_ARCH_X86_64`).
    X86_64,
    /// aarch64 (ARM64) architecture (`AUDIT_ARCH_AARCH64`).
    Aarch64,
    /// riscv64 architecture (`AUDIT_ARCH_RISCV64`).
    Riscv64,
}

impl SystemArch {
    /// Returns the Linux audit architecture constant (`AUDIT_ARCH_*`).
    pub const fn audit_arch(self) -> u32 {
        match self {
            Self::X86_64 => 0xC000_003E,
            Self::Aarch64 => 0xC000_00B7,
            Self::Riscv64 => 0xC000_00F3,
        }
    }
}

/// Pure domain descriptor for a complete Seccomp BPF filter program.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SeccompFilterDescriptor {
    /// Target architecture to enforce.
    pub arch: SystemArch,
    /// Default fallback action if no rule matches.
    pub default_action: SeccompAction,
    /// Ordered list of syscall rules.
    pub rules: Vec<SyscallRule>,
}

impl SeccompFilterDescriptor {
    /// Creates a new seccomp filter with the given architecture and default action.
    pub fn new(arch: SystemArch, default_action: SeccompAction) -> Self {
        Self {
            arch,
            default_action,
            rules: Vec::new(),
        }
    }

    /// Adds a syscall rule to the filter descriptor.
    pub fn add_rule(&mut self, rule: SyscallRule) {
        self.rules.push(rule);
    }

    /// Estimates the total number of classic BPF instructions generated by this filter.
    pub fn estimated_instruction_count(&self) -> usize {
        // Architecture verification: ~4 instructions (load arch, check, jump)
        let mut count = 4;

        // Load syscall nr: 1 instruction
        count += 1;

        // Each rule: check syscall_nr (1-2), each comparison (2-4), action return (1)
        for rule in &self.rules {
            count += 2; // syscall nr check + jump
            count += rule.comparisons.len() * 4; // argument loads and comparisons
            count += 1; // return action
        }

        // Fallback default action: 1 instruction
        count += 1;

        count
    }

    /// Validates seccomp filter invariants.
    pub fn validate(&self) -> Result<(), DomainError> {
        let est_instructions = self.estimated_instruction_count();
        // Maximum instruction count for classic seccomp BPF filters is 4096 (BPF_MAXINSNS)
        if est_instructions > 4096 {
            return Err(DomainError::InvalidSeccompFilter {
                reason: "filter exceeds classic BPF limit of 4096 instructions",
            });
        }

        for rule in &self.rules {
            for comp in &rule.comparisons {
                if comp.arg_index > 5 {
                    return Err(DomainError::InvalidSeccompFilter {
                        reason: "argument index exceeds 64-bit ABI register count (0..=5)",
                    });
                }
            }
        }

        Ok(())
    }
}
